const messages: Record<Locale, Record<TranslationKey, string>> = {
	en: english,
	de: german
};

export function resolveLocale(languages?: Iterable<string> | string | null): Locale {
	const candidates = typeof languages === 'string' ? [languages] : Array.from(languages ?? []);
	return candidates.some((language) => language.toLowerCase().startsWith('de')) ? 'de' : 'en';
}

export function translate(
	locale: Locale,
	key: TranslationKey,
	values: TranslationValues = {}
): string {
	return messages[locale][key].replace(/\{(\w+)\}/g, (_, name: string) =>
		String(values[name] ?? `{${name}}`)
	);
}
